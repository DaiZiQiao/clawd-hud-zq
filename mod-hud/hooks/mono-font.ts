/** A character's advance and its contours' unit, in ems. */
export const MONO_ADVANCE = 0.6
const UNIT = 0.005

const decoded = new Map<string, readonly (readonly [number, number])[][] | undefined>()

/** A character's contours in ems, y up; undefined for one the outlines lack. */
const contoursOf = (ch: string): readonly (readonly [number, number])[][] | undefined => {
  if (decoded.has(ch)) return decoded.get(ch)
  const contours = OUTLINES[ch]?.split(';').map(ring => {
    const steps = ring.split(',').map(Number)
    const points: [number, number][] = []
    let x = 0
    let y = 0
    for (let at = 0; at + 1 < steps.length; at += 2) {
      x += steps[at] ?? 0
      y += steps[at + 1] ?? 0
      points.push([x * UNIT, y * UNIT])
    }

    return points
  })
  decoded.set(ch, contours)

  return contours
}

/**
 * A line of text in JetBrains Mono, `em` units to the em, a character every
 * MONO_ADVANCE em from `x`, on `baseline`: each character a polygon (its
 * holes and other parts its rings), painted by its index. A character the
 * outlines lack (a space too) keeps its place and draws nothing.
 */
export const monoShapes = (text: string, x: number, baseline: number, em: number, paint: (index: number) => Pick<Shape, 'fill' | 'alpha'>, m?: Matrix): Shape[] =>
  [...text].flatMap((ch, index): Shape[] => {
    const contours = contoursOf(ch)
    if (contours === undefined || contours.length === 0) return []
    const left = x + index * MONO_ADVANCE * em
    const [points, ...rings] = contours.map(ring => ring.map(([px, py]): [number, number] => [left + px * em, baseline - py * em]))

    return [{ kind: 'poly', x: 0, y: 0, w: 0, h: 0, points, ...(rings.length === 0 ? {} : { rings }), ...paint(index), ...(m === undefined ? {} : { m }) }]
  })
